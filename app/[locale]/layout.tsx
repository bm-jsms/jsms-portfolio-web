import type { Metadata } from 'next';

import { hasLocale, NextIntlClientProvider } from 'next-intl';
import { notFound } from 'next/navigation';
import { locale as getRootLocale } from 'next/root-params';

import { routing } from '@/i18n/routing';

import '../globals.css';

import { LeftSidebar } from '@/components/LeftSidebar';
import { RightSidebar } from '@/components/RightSidebar';
import { Banner } from '@/components/Banner';
import { MobileNavbar } from '@/components/sidebar/MobileNavbar';

type Props = {
	children: React.ReactNode;
};

export function generateStaticParams() {
	return routing.locales.map((locale) => ({ locale }));
}

export const metadata: Metadata = {
	title: 'Create Next App',
	description: 'Generated by create next app',
};

export default async function RootLayout({ children }: Props) {
	const locale = await getRootLocale();

	if (!hasLocale(routing.locales, locale)) {
		notFound();
	}

	return (
		<html lang={locale} className={`h-full antialiased`}>
			<body className='h-screen flex flex-col bg-gray-950'>
				<NextIntlClientProvider>
					<div className='hidden md:flex flex-1 overflow-hidden'>
						<LeftSidebar />
						<main className='flex-1 overflow-y-auto h-screen overflow-y-auto scrollbar-hide'>
							<div className='mx-auto w-full max-w-5xl px-6 pt-6 sm:px-8'>
								<Banner />
							</div>

							{children}
						</main>
						<RightSidebar style='min-w-[180px] max-w-[240px] w-1/5 max-lg:hidden' />
					</div>

					<div className='flex min-h-0 flex-1 flex-col md:hidden'>
						<MobileNavbar />

						<main className='min-h-0 flex-1 overflow-y-auto overscroll-contain scrollbar-hide'>
							<div className='mx-auto w-full max-w-5xl px-6 pt-6 sm:px-8'>
								<Banner />
							</div>

							{children}
						</main>
					</div>
				</NextIntlClientProvider>
			</body>
		</html>
	);
}
